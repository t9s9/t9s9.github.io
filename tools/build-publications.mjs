#!/usr/bin/env node
/*
  Writes the publication list from publications.json into index.html.

      node tools/build-publications.mjs           rebuild index.html
      node tools/build-publications.mjs --check   fail if it is out of date

  Why this exists: the list used to be fetched and rendered entirely in the
  browser, so the served HTML contained no paper titles at all — invisible to
  every crawler that does not run JS, which is most of them apart from Google.
  The markup now ships in index.html and publications.js hydrates it in place.

  publications.json stays the only place papers are edited. Run this after every
  change to it, or the page and the data drift apart (--check catches that).

  The markup comes from renderList() in publications.js — the same function the
  browser calls — so there is one renderer, not two that can disagree.
*/

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HTML = path.join(ROOT, 'index.html');
const DATA = path.join(ROOT, 'publications.json');

const BEGIN = '<!-- publications:begin — generated by tools/build-publications.mjs from publications.json; do not edit by hand -->';
const END = '<!-- publications:end -->';

// publications.js is an ES module in a .js file; Node only detects that on its own
// from v22. Fail with something more useful than a syntax error on older runtimes.
const major = Number(process.versions.node.split('.')[0]);
if (major < 22) {
  console.error(`Node ${process.versions.node} is too old — this needs Node 22+ (or run it with --experimental-detect-module).`);
  process.exit(1);
}

const { prepare, renderList, DEFAULT_VIEW, hasRelevantSplit } =
  await import(new URL('../publications.js', import.meta.url));

const check = process.argv.includes('--check');
const data = prepare(JSON.parse(await readFile(DATA, 'utf8')));
const html = await readFile(HTML, 'utf8');

const start = html.indexOf(BEGIN);
const stop = html.indexOf(END);
if (start === -1 || stop === -1 || stop < start) {
  console.error(`Could not find the publications markers in ${path.relative(ROOT, HTML)}.`);
  console.error(`Expected:\n  ${BEGIN}\n  …\n  ${END}`);
  process.exit(1);
}

// The page starts in DEFAULT_VIEW, so that is the view that belongs in the HTML.
// Without a usable relevant/all split the page falls back to showing everything,
// and the built markup has to make the same choice.
const view = hasRelevantSplit(data).usable ? DEFAULT_VIEW : { ...DEFAULT_VIEW, showAll: true };
const { html: list, count } = renderList(data, view);

const next = html.slice(0, start + BEGIN.length) + list + '\n    ' + html.slice(stop);

if (next === html) {
  console.log(`index.html is up to date — ${count} publications.`);
  process.exit(0);
}

if (check) {
  console.error('index.html is out of date with publications.json. Run: node tools/build-publications.mjs');
  process.exit(1);
}

await writeFile(HTML, next);
const groups = (data.groups || []).length;
console.log(`Wrote ${count} publications (${groups} groups, ${view.showAll ? 'all' : 'relevant only'}) into index.html.`);
